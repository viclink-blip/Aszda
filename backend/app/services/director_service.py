"""The AI Film Director: Claude plans a film, then each scene's image, video and voice are
generated by the providers configured for that kind of work.

Every step is an ordinary generation job (credits reserved first, refunded on failure,
idempotent), so nothing here bypasses the credit rules. The user reviews the plan before it
is added to the project, and chooses which scenes to generate.
"""

from __future__ import annotations

import uuid
from typing import Any

from sqlalchemy import func, select

from app.errors import APIError, Conflict, NotFound
from app.extensions import db
from app.models import Character, GenerationJob, GenerationKind, JobStatus, Project, Scene, User
from app.services import generation_service, orchestrator, project_service

SCENE_KINDS = {"image": GenerationKind.IMAGE, "video": GenerationKind.VIDEO, "voice": GenerationKind.SPEECH}


def start_plan(user: User, project: Project, *, idea: str, idempotency_key: str, provider: str | None,
               model: str | None, max_output_tokens: int, effort: str) -> tuple[GenerationJob, bool]:
    prompt = idea
    if project.description:
        prompt = f"Project: {project.title}\n{project.description}\n\nIdea:\n{idea}"
    return generation_service.create_job(
        user, idempotency_key=idempotency_key, provider=provider, model=model, kind=GenerationKind.TEXT,
        params={"task": "director_plan", "prompt": prompt[:12000], "max_output_tokens": max_output_tokens,
                "effort": effort},
        project_id=project.id, scene_id=None)


def apply_plan(user: User, project: Project, job_id: uuid.UUID) -> list[Scene]:
    """Add a finished plan's characters and scenes to the project (once per plan)."""
    # Lock the project so two clicks cannot add the scenes twice.
    db.session.execute(select(Project.id).where(Project.id == project.id).with_for_update())
    job = db.session.get(GenerationJob, job_id)
    if job is None or job.user_id != user.id or job.project_id != project.id:
        raise NotFound("Plan not found in this project.")
    if job.status != JobStatus.COMPLETED or not (job.result or {}).get("plan"):
        raise Conflict("This job has no finished film plan.", code="plan_not_ready")
    applied = list((project.brief or {}).get("director_applied_jobs", []))
    if str(job.id) in applied:
        raise Conflict("This plan was already added to the project.", code="plan_already_applied")
    plan = job.result["plan"]

    existing = {c.name.lower(): c for c in project.characters}
    for entry in plan.get("characters", []):
        name = (entry.get("name") or "").strip()[:80]
        if not name or name.lower() in existing:
            continue
        character = Character(project_id=project.id, name=name, description=entry.get("description") or "",
                              traits={"voice": entry.get("voice") or "", "source": "ai_director"})
        db.session.add(character)
        existing[name.lower()] = character
    db.session.flush()

    position = db.session.scalar(select(func.coalesce(func.max(Scene.position) + 1, 0))
                                 .where(Scene.project_id == project.id))
    style = plan.get("style") or ""
    scenes = []
    for offset, entry in enumerate(plan.get("scenes", [])):
        scene = Scene(
            project_id=project.id, position=position + offset, title=entry["title"],
            description=entry.get("description") or "", shot_notes=entry.get("shot") or "",
            dialogue=entry.get("dialogue") or "", duration_seconds=entry["duration_seconds"],
            ai_prompts={"image_prompt": entry.get("image_prompt") or "",
                        "video_prompt": entry.get("video_prompt") or "",
                        "narration": entry.get("narration") or "", "style": style,
                        "plan_job_id": str(job.id)})
        scene.characters = [existing[n.lower()] for n in entry.get("characters", []) if n.lower() in existing]
        db.session.add(scene)
        scenes.append(scene)
    project.brief = {**(project.brief or {}), "director_applied_jobs": [*applied, str(job.id)],
                     "logline": plan.get("logline"), "style": style}
    db.session.commit()
    return scenes


def _brief(scene: Scene, kind: str, orientation: str) -> dict[str, Any]:
    prompts = scene.ai_prompts or {}
    if kind == "image":
        prompt = prompts.get("image_prompt") or scene.description
    elif kind == "video":
        prompt = prompts.get("video_prompt") or scene.description
    else:
        prompt = ""
    text = " ".join(x for x in (prompts.get("narration"), scene.dialogue) if x).strip()
    return {"prompt": prompt, "style": prompts.get("style") or "", "text": text,
            "duration_seconds": scene.duration_seconds or 6, "orientation": orientation,
            "reference_asset_id": scene.preview_asset_id if kind == "video" else None}


def generate_scene(user: User, project: Project, scene_id: uuid.UUID, *, kinds: list[str],
                   providers: dict[str, str], orientation: str, idempotency_key: str) -> list[dict]:
    """Start one job per requested kind for a scene. Each job is routed by the orchestrator
    (or uses the provider the user picked) and has its own derived idempotency key, so
    repeating the request returns the same jobs instead of charging again."""
    scene = project_service.get_scene(project, scene_id)
    results = []
    for kind in kinds:
        generation_kind = SCENE_KINDS[kind]
        brief = _brief(scene, kind, orientation)
        if kind == "voice" and not brief["text"]:
            results.append({"kind": kind, "skipped": "This scene has no narration or dialogue."})
            continue
        if kind != "voice" and not brief["prompt"]:
            results.append({"kind": kind, "skipped": "This scene has no prompt or description."})
            continue
        chosen = orchestrator.route(generation_kind, providers.get(kind))
        params = chosen.adapter.params_for_brief(chosen.spec, brief)
        params = {k: v for k, v in params.items() if v is not None}
        try:
            job, created = generation_service.create_job(
                user, idempotency_key=f"{idempotency_key}:{kind}"[:128], provider=chosen.adapter.name,
                model=chosen.spec.id, kind=generation_kind, params=params, project_id=project.id,
                scene_id=scene.id)
        except APIError as exc:
            results.append({"kind": kind, "error": {"code": exc.code, "message": exc.message,
                                                     "details": exc.details}})
            continue
        results.append({"kind": kind, "job_id": str(job.id), "created": created,
                        "provider": job.provider, "model": job.model})
    return results
