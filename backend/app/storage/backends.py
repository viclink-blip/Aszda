"""Storage backends: the local filesystem (development) and S3-compatible object storage.

Keys are always generated by the server ("users/<uuid>/assets/<uuid>.mp4"), so
user-supplied names never reach the filesystem. The local backend still checks
every resolved path stays inside its root, as defence in depth.
"""

from __future__ import annotations

import os
import re
import shutil
from pathlib import Path
from typing import BinaryIO, Protocol

from flask import current_app, url_for
from itsdangerous import BadSignature, SignatureExpired, URLSafeTimedSerializer

_KEY_PATTERN = re.compile(r"^[a-z0-9][a-z0-9/_.-]{0,500}$")


class StorageError(Exception):
    pass


class ObjectMissing(StorageError):
    pass


def validate_key(key: str) -> str:
    if not _KEY_PATTERN.match(key) or ".." in key or key.startswith("/"):
        raise StorageError("Invalid storage key")
    return key


class Storage(Protocol):
    def save(self, key: str, stream: BinaryIO, content_type: str) -> None: ...
    def open(self, key: str) -> BinaryIO: ...
    def delete(self, key: str) -> None: ...
    def exists(self, key: str) -> bool: ...
    def download_url(self, key: str, *, filename: str, content_type: str) -> str: ...


class LocalStorage:
    def __init__(self, root: str):
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        path = (self.root / validate_key(key)).resolve()
        if self.root not in path.parents:
            raise StorageError("Path escapes storage root")
        return path

    def save(self, key: str, stream: BinaryIO, content_type: str) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        tmp = path.with_suffix(path.suffix + ".part")
        with open(tmp, "wb") as out:
            shutil.copyfileobj(stream, out, length=1024 * 1024)
        os.replace(tmp, path)

    def open(self, key: str) -> BinaryIO:
        path = self._path(key)
        if not path.is_file():
            raise ObjectMissing(key)
        return open(path, "rb")

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()

    def path_for(self, key: str) -> Path:
        return self._path(key)

    def download_url(self, key: str, *, filename: str, content_type: str) -> str:
        # A signed, short-lived link served by the API itself (see api/files.py).
        token = _file_serializer().dumps({"k": key, "f": filename, "t": content_type})
        return url_for("files.serve_signed_file", token=token)


class S3Storage:
    """Works with AWS S3 and S3-compatible services (Cloudflare R2, MinIO, Wasabi...)."""

    def __init__(self, bucket: str, region: str | None, endpoint_url: str | None,
                 access_key: str | None, secret_key: str | None):
        import boto3

        self.bucket = bucket
        self.client = boto3.client(
            "s3", region_name=region or None, endpoint_url=endpoint_url,
            aws_access_key_id=access_key, aws_secret_access_key=secret_key,
        )

    def save(self, key: str, stream: BinaryIO, content_type: str) -> None:
        # Objects are private; access is only through short-lived presigned URLs.
        self.client.upload_fileobj(stream, self.bucket, validate_key(key),
                                   ExtraArgs={"ContentType": content_type})

    def open(self, key: str) -> BinaryIO:
        from botocore.exceptions import ClientError

        try:
            obj = self.client.get_object(Bucket=self.bucket, Key=validate_key(key))
        except ClientError as exc:
            raise ObjectMissing(key) from exc
        return obj["Body"]

    def delete(self, key: str) -> None:
        self.client.delete_object(Bucket=self.bucket, Key=validate_key(key))

    def exists(self, key: str) -> bool:
        from botocore.exceptions import ClientError

        try:
            self.client.head_object(Bucket=self.bucket, Key=validate_key(key))
            return True
        except ClientError:
            return False

    def download_url(self, key: str, *, filename: str, content_type: str) -> str:
        safe_name = re.sub(r'[^A-Za-z0-9._ -]', "_", filename)[:120] or "download"
        return self.client.generate_presigned_url(
            "get_object",
            Params={
                "Bucket": self.bucket, "Key": validate_key(key),
                "ResponseContentType": content_type,
                "ResponseContentDisposition": f'inline; filename="{safe_name}"',
            },
            ExpiresIn=current_app.config["SIGNED_URL_TTL_SECONDS"],
        )


def _file_serializer() -> URLSafeTimedSerializer:
    return URLSafeTimedSerializer(current_app.config["SECRET_KEY"], salt="aszda-file-link")


def read_signed_file_token(token: str) -> dict:
    try:
        return _file_serializer().loads(token, max_age=current_app.config["SIGNED_URL_TTL_SECONDS"])
    except SignatureExpired as exc:
        raise StorageError("expired") from exc
    except BadSignature as exc:
        raise StorageError("invalid") from exc


_instances: dict[str, Storage] = {}


def get_storage() -> Storage:
    cfg = current_app.config
    backend = cfg["STORAGE_BACKEND"]
    cache_key = f"{backend}:{cfg['LOCAL_STORAGE_ROOT']}:{cfg['S3_BUCKET']}"
    if cache_key not in _instances:
        if backend == "local":
            _instances[cache_key] = LocalStorage(cfg["LOCAL_STORAGE_ROOT"])
        elif backend == "s3":
            _instances[cache_key] = S3Storage(cfg["S3_BUCKET"], cfg["S3_REGION"], cfg["S3_ENDPOINT_URL"],
                                              cfg["S3_ACCESS_KEY_ID"], cfg["S3_SECRET_ACCESS_KEY"])
        else:
            raise RuntimeError(f"Unknown ASZDA_STORAGE_BACKEND '{backend}'")
    return _instances[cache_key]
